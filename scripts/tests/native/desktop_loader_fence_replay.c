/* Portable lifecycle replay of exact extracted backend fence/close functions.
 * OS/libbpf calls below are inert; no descriptors, children or devices exist. */
#include "loader.h"
#include <signal.h>
#include <stdarg.h>
#include <stdio.h>
#include <string.h>

#define SYS_pidfd_send_signal 424
struct lantern_linux {
    int fenced, released;
    struct lantern_child owned_child;
    void *links[LANTERN_HOOK_COUNT], *object, *map;
    int shell_fd, pin_dir_fd, exec_error_fd, map_fd;
};
static unsigned signals, closes, links_closed, objects_closed, checks;
static int wrong_signal;
#define CHECK(x) do { checks++; if (!(x)) { fprintf(stderr, "fence check failed line %d\n", __LINE__); return 1; } } while (0)
static long syscall(long number, ...)
{
    va_list args; va_start(args, number);
    int fd = va_arg(args, int), sig = va_arg(args, int);
    va_end(args);
    if (number != SYS_pidfd_send_signal || fd != 7 || sig != SIGKILL) wrong_signal = 1;
    signals++; return 0;
}
static int close(int fd) { (void)fd; closes++; return 0; }
static void bpf_link__destroy(void *pointer) { (void)pointer; links_closed++; }
static void bpf_object__close(void *pointer) { (void)pointer; objects_closed++; }

/* Generated by the Python test from the actual source, never hand-copied. */
#include "backend_fence_close.inc"

static void init(struct lantern_linux *c)
{
    memset(c, 0, sizeof(*c));
    c->owned_child = (struct lantern_child){7, 123, 456, 99};
    c->shell_fd = 8; c->pin_dir_fd = 9; c->exec_error_fd = 10;
    c->object = c; c->links[0] = c;
    signals = closes = links_closed = objects_closed = 0;
    wrong_signal = 0;
}
int main(void)
{
    struct lantern_linux c;
    struct lantern_loader s = {0};
    struct lantern_ops ops = {0}; ops.fence = fence;
    init(&c); s.child = c.owned_child; s.release_attempted = 1;
    s.phase = LANTERN_FROZEN;
    /* A core attempt can precede the backend's syscall marker. Preserve the
     * stronger uncertainty signal rather than reconstructing it from one bit. */
    lantern_hold(&s, &ops, &c);
    CHECK(s.phase == LANTERN_HELD && c.fenced && c.released && !signals);
    fence(&c, &c.owned_child, 0);
    CHECK(c.released && !signals);
    lantern_linux_close(&c);
    CHECK(c.released && !signals && !wrong_signal);
    CHECK(closes == 4 && links_closed == 1 && objects_closed == 1);
    lantern_linux_close(&c);
    CHECK(!signals && closes == 4 && links_closed == 1 && objects_closed == 1);

    init(&c); c.released = 1;
    fence(&c, &c.owned_child, 0); lantern_linux_close(&c);
    CHECK(c.released && !signals && !wrong_signal);

    init(&c); lantern_linux_close(&c);
    CHECK(!c.released && signals == 1 && !wrong_signal);
    CHECK(closes == 4 && links_closed == 1 && objects_closed == 1);
    lantern_linux_close(&c);
    CHECK(signals == 1 && closes == 4);

    init(&c); fence(&c, &c.owned_child, 0);
    CHECK(!c.released && signals == 1 && !wrong_signal);
    printf("%u extracted backend preservation checks passed; whole_linux_backend_compiled=false\n", checks);
    return 0;
}
